_RECEPTION_STOP = re.compile(
    r"\n\s*(?:"
    r"\d{1,2}\s*[.)]\s*(?:выдача\s+груз|переадресовк|отметк|стоимость|прочие\s+условия)"
    r"|сдач\w*\s+груз"
    r"|выдач\w*\s+груз"
    r"|доставк\w*\s+груз"
    r"|переадресовк"
    r"|отметк\w+\s+грузоотпр"
    # Нижний шаблон формы ТН: «(масса груза брутто в килограммах и метод
    # её определения…)» — всё, что ниже, в разделе «Приём груза» — это
    # инструкция бланка, а не данные накладной.
    r"|\(?\s*масс\w*\s+груза\s+брутто\s+в"
    r")",
    re.IGNORECASE,
)

# Строка считается мусорной, если <30% символов — буквы/цифры, и в ней
# много «технических» символов (скобки/слэши/подчёркивания, длинные серии
# одиночных пробелов).
_RECEPTION_NOISE_CHARS = set("[](){}|\\/=_~^`<>*#$%")


def _looks_noisy(line: str) -> bool:
    s = line.strip()
    if not s:
        return True
    # Строки ≤ 3 символов — одиночные литеры/слоги вроде «Г», «а.», «ГЕР».
    if len(s) <= 3:
        return True
    # Аннотации-пояснения в скобках: «(адрес места погрузки)»,
    # «(заявленные дата и время подачи транспортного средства…)» и т.п.
    # Они пропускаются, т.к. содержат реальные русские слова, но нам не нужны.
    if re.match(r"^\s*\(.+\)\s*$", s):
        return True
    # Начатая, но не закрытая аннотация формы: «(заявленные дата н время
    # подачи транс средетва под по», «(нанменование {ИНН владен».
    # Такие обрывки — чистая разметка бланка, данных в них нет.
    if re.match(r"^\s*\(", s) and ")" not in s:
        return True
    # Шаблонные фразы бланка из раздела «Приём груза» — в любом месте
    # строки, поскольку OCR часто режет их по середине.
    _RECEPTION_TEMPLATE_KW = (
        "инфраструктур", "инструктур",              # «владельца инфраструктуры»
        "пункта погруз", "пункта погруи",           # «пункта погрузки»
        "наименование (инн", "нанменование {инн",   # OCR-варианты
        "владел\u044cца объекта",                  # «владельца объекта»
        "заявленные дата", "заявленные лата",
        "фактические дата", "фактиесские лата",
        "время прибытия под",
        "время убытия",
        "опломбирован",
        "расшифровка подписи",
        "осуществившего погрузку",
        "полномочия лица",
        "принявшего груз",
    )
    low = s.lower()
    for kw in _RECEPTION_TEMPLATE_KW:
        if kw in low:
            return True
    # Украинские буквы/диакритика/встроенные апострофы по токенам.
    if is_noise_line(s):
        return True
    # Нет ни одного «осмысленного» слова (≥ 4 букв подряд), ни даты, ни
    # длинного числа (телефон/ИНН/индекс)? Значит строка — OCR-мусор вроде
    # «11 [3] Т» или «000 д».
    if (not re.search(r"[А-Яа-яЁёA-Za-z]{4,}", s)
            and not re.search(r"\d{2}\.\d{2}\.\d{4}", s)
            and not re.search(r"\d{5,}", s)):
        return True
    alnum = sum(1 for c in s if c.isalnum())
    if alnum == 0:
        return True
    if len(s) >= 4 and alnum / len(s) < 0.3:
        return True
    noise = sum(1 for c in s if c in _RECEPTION_NOISE_CHARS)
    if noise >= 3 and noise / max(len(s), 1) > 0.3:
        return True
    # Подряд идущие короткие «токены» из 1-2 символов — это почти всегда
    # OCR-мусор на границе ячеек таблицы.
    tokens = s.split()
    if len(tokens) >= 4:
        short = sum(1 for t in tokens if len(t) <= 2)
        if short / len(tokens) > 0.6:
            return True
    return False


# --- Классификация строк в «Приёме груза» ---------------------------------

# Индекс + область/респ/край — «141411, обл. Московская, с/п …».
_ADDRESS_POSTCODE = re.compile(r"^\s*\d{6}\b")
# Строки, начинающиеся с сокращённых топонимов — «д. Подолино», «г. Москва».
_ADDRESS_TOPONYM = re.compile(
    r"^\s*(?:д\.|г\.|с\.|пос\.|п\.|обл\.|с/п|с-п|р-н|ул\.|пр\.|пр-т|пер\.|ш\.)",
    re.IGNORECASE,
)
# Признак «продолжения» адреса: название улицы/дома/корпуса в любом месте
# строки. Нужен, когда OCR вывел «Астрономическая ул, дом № 8, корпус 2»
# отдельной строкой без стартового «ул.»/«г.».
_ADDRESS_CONTINUATION = re.compile(
    r"\b(?:ул\.?|пр\.?|пр-т|пер\.?|ш\.?|дом\b|корпус\b|литер\b|стр\.?|каб\.?|"
    r"пом\.?|оф(?:ис)?\.?|этаж\b)",
    re.IGNORECASE,
)
# _ORG_PREFIX определён выше, у extract_org — переиспользуем.
_DATE_ONLY = re.compile(r"^\s*\d{2}\.\d{2}\.\d{4}\s*$")


def _line_kind(line: str) -> str:
    """Тип строки для «Приёма груза»: org | address | date | other."""
    s = line.strip()
    if _DATE_ONLY.match(s):
        return "date"
    if _ORG_PREFIX.match(s):
        return "org"
    if _ADDRESS_POSTCODE.match(s) or _ADDRESS_TOPONYM.match(s):
        return "address"
    # «Продолжение» адреса без стартового маркера: «Астрономическая ул,
    # дом № 8, корпус 2, литер Д». Признак — маркер «ул./дом/корпус/…»
    # в любом месте и нет длинного числа-идентификатора (не ИНН/КПП/тел.).
    if _ADDRESS_CONTINUATION.search(s) and not re.search(r"\d{7,}", s):
        return "address"
    return "other"


def _merge_address_fragments(lines: List[str]) -> List[str]:
    """Склеивает фрагменты одного адреса в одну строку.

    Для двухколоночного OCR типичен порядок: сначала топоним («д. Подолино»),
    потом основная часть с индексом («141411, обл. Московская, с/п …»).
    Мы переставляем их местами и склеиваем через запятую.
    """
    out: List[str] = []
    i = 0
    while i < len(lines):
        cur = lines[i].strip()
        cur_kind = _line_kind(cur)

        # «д. Подолино» в одиночку → ждём следующей строки-адреса с индексом.
        if (cur_kind == "address"
                and _ADDRESS_TOPONYM.match(cur)
                and not _ADDRESS_POSTCODE.match(cur)
                and i + 1 < len(lines)):
            nxt = lines[i + 1].strip().rstrip(",; ")
            if _ADDRESS_POSTCODE.match(nxt):
                out.append(f"{nxt}, {cur}".rstrip(",; "))
                i += 2
                continue

        # «141411, …, с/п …, р-н …,» без населённого пункта, а следующая
        # строка — топоним или улица/дом-корпус: обычный прямой порядок.
        if (cur_kind == "address"
                and _ADDRESS_POSTCODE.match(cur)
                and i + 1 < len(lines)):
            nxt = lines[i + 1].strip()
            nxt_kind = _line_kind(nxt)
            if (nxt_kind == "address"
                    and not _ADDRESS_POSTCODE.match(nxt)):
                cur_clean = cur.rstrip(",; ")
                out.append(f"{cur_clean}, {nxt}".rstrip(",; "))
                i += 2
                continue

        out.append(cur)
        i += 1
    return out


def _split_into_blocks(lines: List[str]) -> List[str]:
    """Формирует блоки «реквизиты — адрес — дата» для сборки через пустую строку.

    Каждый блок — это одна уже самодостаточная строка (или несколько однотипных
    строк, если они идут подряд). Между блоками в итоговой сборке вставляется
    пустая строка, чтобы пользователь в Excel видел адреса отдельно друг от
    друга, а не «в кучу».
    """
    blocks: List[str] = []
    prev_kind: Optional[str] = None
    buf: List[str] = []
    for ln in lines[:12]:
        kind = _line_kind(ln)
        # Склеиваем подряд идущие строки одного типа (на случай нескольких
        # адресов подряд).
        if prev_kind is not None and kind != prev_kind:
            if buf:
                blocks.append("\n".join(buf))
                buf = []
        buf.append(ln)
        prev_kind = kind
    if buf:
        blocks.append("\n".join(buf))
    return blocks


def extract_reception(section_body: str, full_text: str) -> Tuple[str, float]:
    """Приём груза с агрессивной чисткой OCR-шума."""
    if section_body:
        body = _RECEPTION_STOP.split(section_body, maxsplit=1)[0]
        lines = [ln for ln in body.splitlines() if not _looks_noisy(ln)]
        # В выживших строках ещё раз выпиливаем одиночные мусорные токены.
        lines = [strip_garbage_tokens(ln.strip()) for ln in lines]
        # После стрипинга строка может потерять все осмысленные слова — как
        # «000 д» после удаления «"Бекам'тбд». Такие остатки — шум.
        lines = [
            ln for ln in lines
            if ln and len(ln) > 3 and re.search(
                r"[А-Яа-яЁёA-Za-z]{4,}|\d{5,}|\d{2}\.\d{2}\.\d{4}", ln
            )
        ]
        # Склеиваем «висячий» хвост-маркер «Ин»/«ИНН» со следующей строкой:
        # OCR часто ломает «ИНН 7743553262» на «…, Ин» + «7743553262, КПП…».
        joined: List[str] = []
        i = 0
        while i < len(lines):
            cur = lines[i].rstrip(" ,;")
            # Строка кончается на обрубок «Ин»/«ИНН»/«КП»/«КПП» без числа → клеим со следующей.
            # «Ин», «ИНН», «КП», «КПП» и OCR-варианты («КИ», «КН») в конце строки —
            # обрубок, число пришло на следующую строку.
            if (i + 1 < len(lines)
                    and re.search(r"(?:\bИНН?|\bК[ПИН]П?)\s*$", cur, re.IGNORECASE)
                    and re.match(r"\s*\d", lines[i + 1])):
                cur = cur.rstrip() + " " + lines[i + 1].strip()
                i += 1
            joined.append(cur)
            i += 1

        # Строки, оканчивающиеся «висячим» тире («Нетто —», «Брутто —»),
        # без числа справа — это OCR-обрывки таблицы выгрузки; удаляем.
        joined = [
            ln for ln in joined
            if not re.search(r"[\s\u2010-\u2015\-–—]+$", ln)
            or re.search(r"\d", ln.rstrip(" -\u2010\u2011\u2012\u2013\u2014\u2015–—"))
        ]
        joined = [re.sub(r"[\s\u2010-\u2015\-–—]+$", "", ln).strip() for ln in joined]

        # Дедупликация: OCR двухколоночных форм часто даёт два «прочтения»
        # одного и того же блока (ООО «Бекам»… появляется дважды с разными
        # ошибками). Сравниваем по множеству «значащих» токенов — слов 4+
        # букв и чисел 4+ цифр. Порог срабатывания — 2 общих токена (строки
        # ~короткие, 3-й часто потерян из-за OCR-искажений).
        def _sig(s: str) -> set:
            return set(
                t for t in re.findall(r"[А-Яа-яЁёA-Za-z]{4,}|\d{4,}", s.lower())
            )

        kept: List[str] = []
        sigs: List[set] = []
        for ln in joined:
            sg = _sig(ln)
            dup = False
            for prev in sigs:
                if not sg:
                    break
                # 2+ общих значащих токена — дубль; либо весь набор токенов
                # короткой строки уже покрыт прежней строкой (остаток одного
                # числа, например «774301001»).
                if len(sg & prev) >= 2 or (sg and sg.issubset(prev)):
                    dup = True
                    break
            if not dup:
                kept.append(ln)
                sigs.append(sg)

        # Строки с Нетто/Брутто/Объём дублируют данные поля «volume» —
        # в карточке приёма смысла не имеют, убираем.
        kept = [ln for ln in kept if not _VOLUME_KW.search(ln)]

        # Дедуп одинаковых подряд идущих строк (например, «23.07.2022» трижды).
        deduped: List[str] = []
        for ln in kept:
            if deduped and deduped[-1].strip() == ln.strip():
                continue
            deduped.append(ln)
        lines = deduped

        # Мелкая косметика: «Ин» на хвосте → «ИНН» (OCR часто режет 3-ю букву).
        lines = [re.sub(r"\bИн\s+(?=\d)", "ИНН ", ln) for ln in lines]

        # Группируем строки в логические блоки: (1) реквизиты контрагента,
        # (2) адрес места погрузки, (3) дата. Это делается двумя вещами:
        # — склейка фрагментов адреса («141411, обл. Московская, с/п …» +
        #   «д. Подолино»), которые OCR разрывает на две строки из-за
        #   двухколоночного макета;
        # — вставка пустой строки между блоками, чтобы в Excel/логе поле не
        #   читалось «в кучу».
        if lines:
            lines = _merge_address_fragments(lines)
            blocks = _split_into_blocks(lines)
            body_clean = "\n\n".join(blocks)[:1500].strip()
            if body_clean and not is_garbage(body_clean):
                return body_clean, 0.9

    if full_text:
        m = re.search(r"при[ёе]м\s+груз\w*", full_text, re.IGNORECASE)
        if m:
            chunk = full_text[m.end(): m.end() + 1500]
            chunk = _RECEPTION_STOP.split(chunk, maxsplit=1)[0]
            lines = [ln for ln in chunk.splitlines() if not _looks_noisy(ln)]
            cleaned = "\n".join(ln.strip() for ln in lines if ln.strip())[:1200]
            cleaned = clean_value(cleaned, MISSING, GARBAGE)
            if cleaned not in (MISSING, GARBAGE):
                return cleaned, 0.5

    return MISSING, 0.0


