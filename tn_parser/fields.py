# Шаблонные фразы из бланка ТН, которые OCR захватывает как «груз».
# «(отгрузочное наименование груза (для опасных грузов — в соответствии с ДОПОГ/МГ)»,
# «его состояние и», «(наименование груза)» и т.п.
_CARGO_TEMPLATE_RE = re.compile(
    r"отгрузочное\s+наименование\s+груза"
    r"|для\s+опасных\s+груз"
    r"|в\s+соответствии\s+с\s+(?:допог|мг\b)"
    r"|его\s+состояние\s+и\b"
    r"|наименование\s+(?:ИНН\b|груза\b.*\()"  # подсказки в скобках
    # «другая необходимая информация о грузе» — OCR-варианты: «доугая»,
    # «нсобходимая», «© грузе». Работаем по ключевым словам «информац…+груз».
    r"|информац\w*\s+[^а-яё]{0,5}\s*груз"
    r"|необходим\w*\s+информац\w*"
    r"|количество\s+грузовых\s+мест"
    r"|маркировка.*способ\s+упаковки"
    r"|плотность\s+груз"
    r"|дополнительные\s+характеристик"
    r"|кубических\s+метрах"
    r"|отраслевые\s+особенности"
    r"|\(при\s+необходимости"              # шаблонные пометки «(при необходимости)»
    r"|масс\w*\s+груза\s+брутто\s+в"
    r"|объявленн\w*\s+стоимость"
    r"|в\s+случае\s+перевозки\s+опасн"
    r"|изделию\s+в\s+соответств"
    r"|ДОПОГ"
    r"|пункт\w*\s+\d+\.\d+"
    # Заголовок табличного блока формы 1-Т: «№ Наименование товара Ед.изм
    # Кол-во Цена Сумма». Характеризуется комбинацией 2+ канцелярских слов
    # из набора {наименование, ед.изм, кол-во, цена, сумма} в одной строке.
    r"|наименование\s+товара"
    r"|ед\.?\s*изм\.?\s+кол"
    r"|кол-во\s+цена",
    re.IGNORECASE,
)


def extract_cargo(section_body: str, full_text: str) -> Tuple[str, float]:
    """Извлекает наименование груза, снимая префикс «Наименование —»."""
    if section_body:
        lines = _meaningful_lines(section_body)
        cleaned: List[str] = []
        for ln in lines:
            low = ln.lower()

            # Строка — шаблонный текст бланка ТН: пропускаем.
            if _CARGO_TEMPLATE_RE.search(ln):
                continue

            # Строки, начинающиеся с фигурной/квадратной скобки — это
            # шаблонные пояснения формы («{ масса груза брутто в килограммах…»).
            if re.match(r"^\s*[\{\[]", ln):
                continue

            # Строка-заголовок без значения: «1. Нанменование —» (OCR разбил
            # на отдельную строку, значение идёт следующей строкой).
            # Пропускаем её целиком — значение возьмём из следующей строки.
            if re.match(
                r"^\s*(?:\d+[.)]\s*)?н.{1,5}мен\w*\s*[:\-–—\u2010-\u2015\u2212]*\s*$",
                ln, re.IGNORECASE,
            ):
                continue

            # "1. Наименование — Блок облицовочный…" → «Блок облицовочный…»
            # Допускаем OCR-варианты: «Нанменование», «Наиименование» и т.п.:
            # н + 1–5 произвольных символов + «мен» + хвост.
            m = re.match(
                r"^\s*(?:\d+[.)]\s*)?н.{1,5}мен\w*\s*[:\-–—\u2010-\u2015\u2212]+\s*(.+)$",
                ln, re.IGNORECASE,
            )
            if m and m.group(1).strip():
                cleaned.append(m.group(1).strip())
                continue
            # "Груз: X"
            if low.startswith("груз:") or low.startswith("груз —"):
                parts = re.split(r"[:\-–—]", ln, maxsplit=1)
                if len(parts) == 2 and parts[1].strip():
                    cleaned.append(parts[1].strip())
                continue
            # Пропускаем чисто измерительные строки.
            if re.match(
                r"^(ед\.\s*изм|кол-во|количес|масс|объ[её]м|нетто|брутто|в том числе)\b",
                low,
            ):
                continue
            # Строки с весовыми/объёмными ключевыми словами в любом месте строки
            # при наличии цифр — это измерительные данные, а не наименование груза.
            # Пример: «20,52 т., Брутто —», «20,835 т., Объем —» (OCR разбил на части).
            if _VOLUME_KW.search(ln) and re.search(r"\d", ln):
                continue
            # Пропускаем строки без единой буквы (только числа и знаки —
            # обычно «20,52 т., 20,835 т., 8,73 м³»).
            if not re.search(r"[А-Яа-яЁёA-Za-z]{3,}", ln):
                continue
            cleaned.append(ln)

        if cleaned:
            # Нумерованные позиции «1. …», «2. …», «3. …» в накладных
            # встречаются двумя способами: (а) отдельными строками,
            # (б) слитно одной строкой из-за плотного OCR («… 6,146 2.
            # Одноосная …»). Ищем маркеры «N.» в любом месте каждой
            # строки — если их два и больше, раскладываем позиции по
            # отдельным строкам для читаемости в Excel.
            _NUM_ITEM = re.compile(r"(?<!\d)\d+[.)]\s+[А-ЯЁA-Zа-яёa-z]")
            total_numbered = sum(
                len(_NUM_ITEM.findall(ln)) for ln in cleaned
            )
            if total_numbered >= 2:
                split_cleaned: List[str] = []
                for ln in cleaned:
                    # Разрыв перед каждой следующей «N. Слово» внутри строки.
                    parts = re.split(
                        r"(?<=\S)\s+(?=\d+[.)]\s+[А-ЯЁA-Zа-яёa-z])", ln
                    )
                    split_cleaned.extend(p.strip() for p in parts if p.strip())
                joined = "\n".join(split_cleaned[:15])[:1500].strip(" ,;")
            else:
                joined = " ".join(cleaned[:3])
                joined = joined[:400].strip(" ,;")
            if joined and not is_garbage(joined):
                return joined, 0.9

    if full_text:
        for pat in (
            r"наименовани\w*\s+груз\w*\s*[:\-–—\u2010-\u2015\u2212]+\s*([^\n\r]{2,400})",
            r"наименовани\w*\s*[:\-–—\u2010-\u2015\u2212]+\s*([^\n\r]{2,400})",
        ):
            m = re.search(pat, full_text, re.IGNORECASE)
            if m:
                candidate = m.group(1).strip()[:400]
                if candidate and not is_garbage(candidate):
                    return candidate, 0.5

    return MISSING, 0.0


_VOLUME_KW = re.compile(r"\b(нетто|брутто|объ[её]м|масс[аы]|вес\b)", re.IGNORECASE)
_VOLUME_NUM = re.compile(r"\d")

# Количество товара на строке наименования груза: «720 шт», «15 паллет», «50 упак.»
# Используется как запасной вариант для объёма, когда нет строк Нетто/Брутто.
_QTY_ON_CARGO_LINE = re.compile(
    r"\b(\d+(?:[.,\s]\d+)*)\s*"
    r"(шт\.?|штук[аи]?|уп\.?|упак\.?|упаковк[аи]?"
    r"|паллет[аы]?|пал\.?|поддон[аы]?"
    r"|коробк[аи]?|ящик[аи]?|мешк[аи]?"
    r"|рул[яей]?|единиц[аы]?)\b",
    re.IGNORECASE,
)


def extract_volume(section_body: str, full_text: str) -> Tuple[str, float]:
    """Извлекает строку с весом/объёмом груза (Нетто/Брутто/Объём)."""
    if section_body:
        # OCR часто бьёт «Нетто — 20,52 т., Брутто — 20,835 т.» на несколько
        # строк, где каждая заканчивается на «—» (незакрытое тире).
        # Склеиваем такие строки в одну перед поиском.
        raw_lines = section_body.splitlines()
        joined: List[str] = []
        i = 0
        while i < len(raw_lines):
            s = raw_lines[i].rstrip()
            while re.search(r"[–—]\s*$", s) and i + 1 < len(raw_lines):
                i += 1
                nxt = raw_lines[i].strip()
                if nxt:
                    s = s.rstrip() + " " + nxt
            joined.append(s.strip())
            i += 1

        for s in joined:
            if _VOLUME_KW.search(s) and _VOLUME_NUM.search(s):
                # Снимаем «висячее» тире в конце («… Брутто —»).
                s = re.sub(r"[\s\u2010-\u2015\-–—]+$", "", s).strip()
                if s and not is_garbage(s):
                    return s, 0.9

        # Запасной вариант: количество на строке наименования груза
        # («720 шт», «15 паллет»). Применяется только если строк Нетто/Брутто нет.
        for s in joined:
            m = _QTY_ON_CARGO_LINE.search(s)
            if m and not _VOLUME_KW.search(s):
                qty = m.group(0).strip()
                if qty and not is_garbage(qty):
                    return qty, 0.6

    if full_text:
        for m in _VOLUME_KW.finditer(full_text):
            ls = full_text.rfind("\n", 0, m.start())
            ls = 0 if ls < 0 else ls + 1
            le = full_text.find("\n", m.end())
            le = len(full_text) if le < 0 else le
            ln = full_text[ls:le].strip()
            if _VOLUME_NUM.search(ln) and not is_garbage(ln):
                return ln, 0.5
    return MISSING, 0.0


