# -*- coding: utf-8 -*-
"""Извлечение конкретных полей из разделов ТН.

Принцип: сначала ищем поле в «своём» разделе (высокая уверенность), если
нет — падаем на эвристики по всему тексту (низкая уверенность). Каждый
экстрактор возвращает кортеж (value, confidence).

Сложности реального OCR:
- В таблице заголовок ячейки и её значение — на разных «логических» строках.
- Ячейки с двумя колонками (способ | ФИО, марка | ГРЗ) после извлечения
  разворачиваются в две соседние строки.
- Пояснения в скобках («(реквизиты, позволяющие идентифицировать…)») и
  формульные подсказки (« является экспедитором», « (а) … ») — мусор.

Экстракторы ниже стараются это учесть.


==============================================================================
ГДЕ ЛЕЖИТ КАЖДОЕ ПОЛЕ И ГДЕ ОНО ЗАКАНЧИВАЕТСЯ
==============================================================================

number / date
    ЛЕЖИТ: в «шапке» документа, рядом со словами «Транспортная накладная».
           Чаще всего формат: «№ 2908-23А от 29.08.2022» или в табличной
           ячейке «Дата | DD.MM.YYYY | № | XXXXX».
    ГРАНИЦА: первый раздел «1. Грузоотправитель».
    ПРАВИЛО: «Экземпляр №» перед номером — шум, пропускаем.

shipper (грузоотправитель)
    ЛЕЖИТ: раздел «1. Грузоотправитель». Обычно 1–3 строки:
        — ООО/АО/ИП название («ООО "Ромашка"»),
        — адрес (индекс, город, улица, дом, помещение),
        — ИНН, опционально КПП, иногда ОГРН, иногда телефон.
    ГРАНИЦА: раздел «2. Грузополучатель» или «ИНН <длинное число>» в
             конце; висячий ярлык «КПП» без числа срезается.
    ПРАВИЛА:
        — «является экспедитором» и производные — шум.
        — «(реквизиты, позволяющие идентифицировать Грузоотправителя)»
          и OCR-варианты — шум.
        — В форме 1-Т ярлык и значение на одной строке через пробелы:
          «Грузоотправитель  ООО Ромашка, …».

consignee (грузополучатель)
    ЛЕЖИТ: раздел «2. Грузополучатель». Структура — как у shipper.
    ГРАНИЦА: раздел «3. Груз».
    ПРАВИЛА: те же, что у shipper, только про «Грузополучателя».

cargo (груз)
    ЛЕЖИТ: раздел «3. Груз». Два варианта:
        (а) Одна строка: «1. Наименование — <товар>».
        (б) Таблица с колонками «№ / Наименование / Ед.изм / Кол-во /
            Цена / Сумма» — тогда в cargo попадают ПРОНУМЕРОВАННЫЕ позиции
            на отдельных строках.
    ГРАНИЦА: раздел «4. Сопроводительные документы».
    ПРАВИЛА:
        — Шапка таблицы — шум.
        — «{ масса груза брутто …}» и подобные подсказки бланка — шум.
        — Весовые строки «Нетто/Брутто/Объём» НЕ попадают в cargo —
          это поле volume.
        — Если в cargo несколько позиций «1. …», «2. …», «3. …»
          (даже слитых в одну строку) — раскладываем по строкам.

volume (вес / объём)
    ЛЕЖИТ: в конце раздела «3. Груз». Чаще: «Нетто — 20,52 т., Брутто —
           20,835 т., Объём 8,73 м³». Иногда разбито на несколько строк.
    FALLBACK: если отсутствует, берём количество на строке cargo
              («720 шт», «50 паллет») — это грубая замена.

carrier (перевозчик)
    ЛЕЖИТ: раздел «Перевозчик» (номер раздела плавает). В современной ТН
           обычно двухколоночный:
        ЛЕВАЯ колонка: юрлицо-перевозчик (ООО/ИП + ИНН + адрес + телефон).
        ПРАВАЯ колонка: ФИО водителя, реквизиты паспорта.
    ИТОГ: приоритет — ФИО водителя. При самовывозе и в форме 1-Т
          (где «Водитель» — отдельный раздел) ищем ФИО по ярлыку
          «Водитель:» в полном тексте.
    ГРАНИЦА: раздел «Транспортное средство».
    ПРАВИЛА:
        — «Самовывоз» сам по себе — признак «юрлица нет», забираем
          только водителя.
        — «(реквизиты … идентифицировать Перевозчика)» — шум.

vehicle (транспортное средство)
    ЛЕЖИТ: раздел «Транспортное средство». Часто марка + ГРЗ:
           «RENAULT   Р 814 НР 152».
    ИТОГ: ТОЛЬКО ГРЗ в каноническом формате «Р 814 НР 152». Марку
          не берём — OCR регулярно «накладывает» кириллицу поверх
          латиницы («RENAULT» → «ВРМАЗЕТ»), и значение становится
          неразборчивым.
    ГРАНИЦА: раздел «Приём груза» или «Стоимость перевозки».

reception (приём груза)
    ЛЕЖИТ: раздел «Приём груза» (или «Пункт погрузки» в 1-Т).
           Блок из трёх частей:
        1. Реквизиты лица, осуществляющего погрузку (ООО, адрес, ИНН).
        2. Адрес места погрузки (индекс + область + населённый пункт).
        3. Даты подачи/прибытия/убытия (dd.mm.yyyy).
    ГРАНИЦА: раздел «9. Переадресовка» или «10. Выдача груза», либо
             шаблон «(масса груза брутто в килограммах и метод …)».
    ПРАВИЛА:
        — OCR-дубли блока с разной степенью порчи — одно прочтение
          оставляем, остальные дедупим.
        — «(адрес места погрузки)», «(фактические дата …)» —
          шаблон бланка, не значение.
        — «Инфраструктур», «пункта погруз», «расшифровка подписи» —
          тоже шаблон.
        — Выводим тремя блоками через пустую строку для читаемости:
          компания / адрес / дата.
"""

